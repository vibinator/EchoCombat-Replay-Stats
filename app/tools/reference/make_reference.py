"""Generate the token-saving reference files in docs/reference/ from the code itself (user, 2026-11-07).

    python app/tools/reference/make_reference.py

Writes (all regenerated, never edit by hand):
- docs/reference/SYMBOLS.md      every Python file: lines, first docstring line, top-level classes / functions with line numbers
- docs/reference/API-ROUTES.md   every HTTP route: method, path, handler, file:line, first docstring line
- docs/reference/FRONTEND-MAP.md every React page / component / hook: exports with line numbers, which api.ts calls it uses
- docs/reference/CSS-MAP.md      the section comments of styles.css with line numbers (what lives where)
- docs/reference/TESTS-MAP.md    every test file: the test names, so a change can be matched to its tests
Run it after a change set, before bump_version.py; the files are small and diff cleanly."""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "docs" / "reference"
BACKEND = ["app/backend", "app/parser", "app/admin_console.py", "app/remote_worker.py", "app/bump_version.py",
           "app/cloudflare_check.py", "app/sync_recent_replays.py", "app/tools"]
FRONTEND = ROOT / "app" / "frontend" / "src"
TESTS = ROOT / "tests"
NL = "\n"


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def py_files():
    for entry in BACKEND:
        p = ROOT / entry
        if p.is_file():
            yield p
        elif p.is_dir():
            yield from sorted(x for x in p.rglob("*.py") if "node_modules" not in x.parts and "__pycache__" not in x.parts)


def first_line(doc) -> str:
    if not doc:
        return ""
    line = doc.strip().splitlines()[0].strip()
    return (line[:150] + "...") if len(line) > 150 else line


def symbols() -> str:
    lines = ["# Symbols (generated by app/tools/reference/make_reference.py - do not edit)", "",
             "One block per Python file: `path (N lines)`, its purpose, then top-level classes / functions as `name:line`",
             "(class methods in brackets, UPPER_CASE constants in backticks). Open a file only at the line you need;",
             "Architecture.MD / DataModel.MD explain the why.", ""]
    for p in py_files():
        src = p.read_text(encoding="utf-8", errors="replace")
        try:
            tree = ast.parse(src)
        except SyntaxError as e:
            lines.append(f"- `{rel(p)}` - SYNTAX ERROR {e}")
            continue
        lines.append(f"### `{rel(p)}` ({src.count(NL) + 1} lines)")
        doc = first_line(ast.get_docstring(tree))
        if doc:
            lines.append(doc)
        items = []
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                methods = [f"{m.name}:{m.lineno}" for m in node.body
                           if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and not m.name.startswith("__")]
                items.append(f"**class {node.name}**:{node.lineno}" + (f" [{', '.join(methods)}]" if methods else ""))
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                items.append(f"{node.name}:{node.lineno}")
            elif (isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name)
                  and node.targets[0].id.isupper()):
                items.append(f"`{node.targets[0].id}`:{node.lineno}")
        if items:
            lines.append("- " + " / ".join(items))
        lines.append("")
    return NL.join(lines)


ROUTE = re.compile(r'@(?P<router>\w+)\.(?P<method>get|post|put|delete|patch)\(\s*"(?P<path>[^"]*)"')
PREFIX = re.compile(r'(?P<name>\w+)\s*=\s*APIRouter\(\s*prefix="(?P<prefix>[^"]*)"')
DEF = re.compile(r"\s*(?:async\s+)?def\s+(\w+)")


def routes() -> str:
    rows = []
    for p in sorted((ROOT / "app" / "backend").rglob("*.py")):
        src = p.read_text(encoding="utf-8", errors="replace")
        prefixes = {m.group("name"): m.group("prefix") for m in PREFIX.finditer(src)}
        text = src.splitlines()
        for m in ROUTE.finditer(src):
            line_no = src.count(NL, 0, m.start()) + 1
            handler, doc = "?", ""
            for i in range(line_no, min(line_no + 6, len(text))):
                d = DEF.match(text[i])
                if d:
                    handler = d.group(1)
                    for j in range(i + 1, min(i + 4, len(text))):
                        s = text[j].strip()
                        if s.startswith('"""'):
                            doc = s.strip('"').strip()
                            break
                        if s and not s.startswith("#"):
                            break
                    break
            rows.append((prefixes.get(m.group("router"), "") + m.group("path"), m.group("method").upper(), handler,
                         f"{rel(p)}:{line_no}", doc[:110].replace("|", "/")))
    rows.sort()
    out = ["# API routes (generated by app/tools/reference/make_reference.py - do not edit)", "",
           "Guard (backend/guard.py): every `/api/*` request needs a browser User-Agent and `X-EchoVR: 1`",
           "(exempt: /api/auth/*, /api/health, exports, /api/bot/*, /api/worker/*). Writes are refused with 405 unless the",
           "path is in middleware.WRITES / BOT. Console routes need auth.has_console; profile writes need the Discord login.",
           "/api/import and /api/replays exist only with Settings.import_api (tests).", "",
           "| Method | Path | Handler | Where | Purpose |", "|---|---|---|---|---|"]
    out += [f"| {m} | `{path}` | {h} | {where} | {doc} |" for path, m, h, where, doc in rows]
    return NL.join(out) + NL


EXPORT = re.compile(r"^export\s+(?:default\s+)?(?:async\s+)?(?:function|const|class|type|interface|enum)\s+(\w+)", re.M)
API_FUNC = re.compile(r"^export\s+(?:async\s+)?function\s+(\w+)", re.M)
API_CONST = re.compile(r"^export\s+const\s+(\w+)\s*=", re.M)
CALL = re.compile(r"\b(\w+)\(")
ENDPOINT = re.compile(r"[`\"'](/api/[^`\"'$?]*)")


def frontend_map() -> str:
    api_src = (FRONTEND / "api.ts").read_text(encoding="utf-8", errors="replace")
    api_funcs = set(API_FUNC.findall(api_src)) | set(API_CONST.findall(api_src))
    out = ["# Frontend map (generated by app/tools/reference/make_reference.py - do not edit)", "",
           "Each file: lines, its exports with line numbers, and which api.ts functions it calls (= the endpoints it",
           "depends on). Routes are in App.tsx; styling is one file, styles.css (see CSS-MAP.md). No prettier: keep long",
           "lines and CRLF.", ""]
    for p in sorted(FRONTEND.rglob("*.ts*")):
        src = p.read_text(encoding="utf-8", errors="replace")
        exports = [f"{m.group(1)}:{src.count(NL, 0, m.start()) + 1}" for m in EXPORT.finditer(src)]
        calls = sorted({c for c in CALL.findall(src) if c in api_funcs}) if p.name != "api.ts" else []
        out.append(f"### `{rel(p)}` ({src.count(NL) + 1} lines)")
        if exports:
            out.append("- exports: " + ", ".join(exports))
        if calls:
            out.append("- api.ts calls: " + ", ".join(calls))
        out.append("")
    out.append("### api.ts functions -> endpoints (first /api path each one mentions)")
    starts = sorted((m.start(), m.group(1)) for m in list(API_FUNC.finditer(api_src)) + list(API_CONST.finditer(api_src)))
    for (start, name), nxt in zip(starts, [s for s, _ in starts[1:]] + [len(api_src)]):
        found = ENDPOINT.findall(api_src[start:nxt])
        if found:
            out.append(f"- {name} -> `{found[0]}`")
    return NL.join(out) + NL


def css_map() -> str:
    src = (FRONTEND / "styles.css").read_text(encoding="utf-8", errors="replace")
    out = ["# styles.css map (generated by app/tools/reference/make_reference.py - do not edit)", "",
           f"app/frontend/src/styles.css ({src.count(NL) + 1} lines). Section comments with their line numbers; theme",
           "tokens are at the top (:root) and in the light-theme block.", ""]
    for i, line in enumerate(src.splitlines(), 1):
        s = line.strip()
        if s.startswith("/*") and len(s) > 12:
            out.append(f"- {i}: {s.strip('/* ').rstrip('*/ ')[:120]}")
    return NL.join(out) + NL


def tests_map() -> str:
    out = ["# Tests map (generated by app/tools/reference/make_reference.py - do not edit)", "",
           "Run: `.venv\\Scripts\\python -m pytest -q` (about 1 min). One file per feature; the test names say what is",
           "pinned down, so a change can be matched to the tests that cover it.", ""]
    for p in sorted(TESTS.rglob("test_*.py")):
        src = p.read_text(encoding="utf-8", errors="replace")
        try:
            tree = ast.parse(src)
        except SyntaxError:
            continue
        names = [n.name for n in tree.body if isinstance(n, ast.FunctionDef) and n.name.startswith("test_")]
        out.append(f"### `{rel(p)}` ({len(names)} tests)")
        doc = first_line(ast.get_docstring(tree))
        if doc:
            out.append(doc)
        out.append("- " + ", ".join(names))
        out.append("")
    return NL.join(out)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in (("SYMBOLS.md", symbols()), ("API-ROUTES.md", routes()), ("FRONTEND-MAP.md", frontend_map()),
                       ("CSS-MAP.md", css_map()), ("TESTS-MAP.md", tests_map())):
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote docs/reference/{name} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
